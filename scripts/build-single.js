const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const data = require('./content.js').collectContent();
const scenes = require('./scenes.js').collectScenes(data);
let html = read('src/shell.html');
html = html.replace('/* INLINE_STYLES */', () => read('src/style.css')+'\n'+read('src/experience.css')+'\n'+read('src/games/puzzle.css')+'\n'+read('src/games/scene-trails.css')+'\n'+read('src/games/garden.css'));
html = html.replace('"INLINE_SCENES"', () => JSON.stringify(scenes).replace(/</g, '\\u003c'));
html = html.replace('"INLINE_LIBRARY"', () => JSON.stringify(data).replace(/</g, '\\u003c'));
html = html.replace('/* INLINE_DATA */', () => read('src/data/library.js')+'\n'+read('src/data/personal-content.js'));
html = html.replace('"INLINE_LEGACY"', () => read('src/data/legacy-v1-fingerprints.json'));
html = html.replace('/* INLINE_APP */', () => read('src/experience.js')+'\n'+read('src/games/poem-puzzle.js')+'\n'+read('src/games/puzzle-view.js')+'\n'+read('src/games/scene-trails.js')+'\n'+read('src/games/scene-trails-view.js').replace("'INLINE_SCENE_TEMPLATE'", () => JSON.stringify(read('src/games/scene-trails.html')))+'\n'+read('src/games/garden.js')+'\n'+read('src/app.js'));
fs.writeFileSync(path.join(root, 'offline.html'), html);
console.log('Built offline.html · ' + data.works.length + ' works · ' + Math.round(Buffer.byteLength(html) / 1024) + ' KB');

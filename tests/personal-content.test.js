const assert=require('node:assert/strict');
const {collectContent}=require('../scripts/content.js');
const {validateLibrary}=require('../src/data/library.js');
const P=require('../src/data/personal-content.js');
const seed=collectContent(),copy=x=>JSON.parse(JSON.stringify(x)),baseline=P.fingerprints(seed);
const work=(lib,id='jingyesi')=>lib.works.find(w=>w.id===id);
assert.deepEqual(P.diff(seed,seed).groups,{});
const custom=copy(seed);
work(custom).background='我补充的写作背景。';
work(custom).extra.place='我的一处地名。';
custom.modules.push({id:'place',label:'地名',enabled:true});
custom.modules.reverse();
const personal=P.diff(seed,custom);
assert.deepEqual(P.apply(seed,personal).library,custom);
assert.equal(Object.keys(personal.groups.works).length,1,'Only changed works are stored');
const next=copy(seed);
work(next).background='内置背景修订。';
work(next).thought='内置思想修订。';
next.modules.push({id:'more',label:'更多',enabled:true});
next.works.push({...copy(work(seed)),id:'newwork',title:'新增作品'});
const result=P.apply(next,personal);
assert.equal(work(result.library).background,'我补充的写作背景。');
assert.equal(work(result.library).thought,'内置思想修订。');
assert.equal(work(result.library).extra.place,'我的一处地名。');
assert(work(result.library,'newwork'));
assert(result.library.modules.some(m=>m.id==='more'));
assert.deepEqual(result.notices,[{group:'works',id:'jingyesi',field:'background'}]);
const resolved=P.usePublished(next,result.library,result.notices);
assert.equal(work(resolved).background,'内置背景修订。');
assert.equal(work(resolved).extra.place,'我的一处地名。');
assert.deepEqual(P.apply(next,P.diff(next,result.library)).library,result.library,'Re-saving should be stable across updates');

// The frozen v1 baseline identifies unchanged legacy text even if the new seed changed.
const legacy=copy(seed);delete legacy.discovery;
const migrated=P.migrate(next,validateLibrary(legacy,seed),baseline);
assert.equal(work(migrated.library).background,'内置背景修订。');
assert(work(migrated.library,'newwork'));
assert.equal(migrated.notices.length,0);
work(legacy).background='旧版用户的修改。';
legacy.modules[0].enabled=false;
const migratedCustom=P.migrate(next,validateLibrary(legacy,seed),baseline);
assert.equal(work(migratedCustom.library).background,'旧版用户的修改。');
assert.equal(work(migratedCustom.library).thought,'内置思想修订。');
assert.equal(migratedCustom.library.modules[0].enabled,false);

const beforeDelete=copy(seed);work(beforeDelete,'zhushi').background='保留自定义作品。';
const removed=copy(seed),zhushi=work(seed,'zhushi');
removed.works=removed.works.filter(w=>w.id!=='zhushi');
removed.works.forEach(w=>w.related=w.related.filter(r=>r.id!=='zhushi'));
removed.topics.forEach(t=>t.works=t.works.filter(id=>id!=='zhushi'));
delete removed.authors[zhushi.author];
const retained=P.apply(removed,P.diff(seed,beforeDelete));
assert.equal(work(retained.library,'zhushi').background,'保留自定义作品。');
assert(retained.library.authors[zhushi.author]);
assert(retained.notices.some(n=>n.id==='zhushi'&&n.field==='*'));
const adopted=P.usePublished(removed,retained.library,retained.notices);
assert(!work(adopted,'zhushi'));

const bad=copy(personal);bad.groups.works.jingyesi.set=JSON.parse('{"__proto__":{"polluted":true}}');
assert.throws(()=>P.apply(seed,bad),/字段无效/);
assert.equal({}.polluted,undefined);
assert.throws(()=>P.apply(seed,{groups:{unknown:{}}}),/分类无效/);
const config=copy(seed);config.discovery.featuredMark='诗';
assert.equal(P.apply(seed,P.diff(seed,config)).library.discovery.featuredMark,'诗');
console.log('PASS: field-level updates, conflict resolution, legacy migration, custom modules, deleted works and unsafe patches');
